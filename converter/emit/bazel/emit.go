func sortedCopy(in []string) []string {
	if len(in) == 0 {
		return nil
	}
	out := append([]string(nil), in...)
	sort.Strings(out)
	return out
}

// sortedDedup returns a sorted slice with consecutive duplicates
// removed. Cheap for the small slices the emitter typically
// composes (per-attribute fact lists).
func sortedDedup(in []string) []string {
	if len(in) == 0 {
		return nil
	}
	out := append([]string(nil), in...)
	sort.Strings(out)
	w := out[:1]
	for _, x := range out[1:] {
		if x != w[len(w)-1] {
			w = append(w, x)
		}
	}
	return w
}

// strDict renders a Go map[string]string as a Starlark dict literal,
// keys sorted for byte-stable output. Empty maps render as "{}".
func strDict(m map[string]string) string {
	if len(m) == 0 {
		return "{}"
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var single bytes.Buffer
	single.WriteByte('{')
	for i, k := range keys {
		if i > 0 {
			single.WriteString(", ")
		}
		fmt.Fprintf(&single, "%q: %q", k, m[k])
	}
	single.WriteByte('}')
	if single.Len() <= 60 {
		return single.String()
	}
	var multi bytes.Buffer
	multi.WriteString("{\n")
	for _, k := range keys {
		fmt.Fprintf(&multi, "        %q: %q,\n", k, m[k])
	}
	multi.WriteString("    }")
	return multi.String()
}

// strList renders a Go []string as a Starlark list literal:
//
//	["a", "b"]                       (single-line if total <= 60 chars)
//	[
//	    "a",
//	    "b",
//	]                                 (multi-line otherwise)
func strList(items []string) string {
	if len(items) == 0 {
		return "[]"
	}
	// single-line trial. %q escapes embedded quotes / backslashes /
	// control bytes so values like `LZ4_VERSION="1.8.0"` (cmake
	// derives these from add_definitions(-DLZ4_VERSION="1.8.0"))
	// produce valid Starlark string literals instead of unparseable
	// `"LZ4_VERSION="1.8.0""`. Same escaping the multi-line arm
	// already uses; the divergence was a latent bug surfaced by
	// real-world (VTK / lz4) defines.
	var single bytes.Buffer
	single.WriteByte('[')
	for i, s := range items {
		if i > 0 {
			single.WriteString(", ")
		}
		fmt.Fprintf(&single, "%q", s)
	}
	single.WriteByte(']')
	if single.Len() <= 60 {
		return single.String()
	}
	// multi-line
	var multi bytes.Buffer
	multi.WriteString("[\n")
	for _, s := range items {
		fmt.Fprintf(&multi, "        %q,\n", s)
	}
	multi.WriteString("    ]")
	return multi.String()
}

// attrExpr renders one cc-rule attribute's value combining a flat
// baseline list with optional per-platform deltas. Returns:
//
//   - "" when both flat and sel are empty (caller omits the
//     attribute entirely)
//   - strList(flat) when sel is empty (existing single-platform
//     behaviour, byte-identical to the pre-PerPlatform shape)
//   - "select({...})" when only sel is non-empty (no baseline
//     items shared across every platform)
//   - "<flat> + select({...})" when both are non-empty
//
// The select() block always carries a "//conditions:default": []
// arm so a Bazel build under a platform not in the select keys
// resolves to an empty list rather than failing analysis. Arm
// keys are emitted in sorted order so the rendered BUILD.bazel
// is byte-stable across runs (map iteration is randomized).
//
// Arm-list contents are emitted in the caller-supplied order.
// elementfold owns the per-attribute ordering convention: it
// sorts order-insensitive attrs (srcs, hdrs, includes, defines,
// deps) lexicographically and preserves cells' original sequence
// for order-sensitive attrs (copts, linkopts). emit-time
// fan-in (e.g. cc_binary's hdrs→srcs arm merge) is responsible
// for sorting its own merged arms before passing them in.
func attrExpr(flat []string, sel map[string][]string) string {
	hasSel := len(sel) > 0
	hasFlat := len(flat) > 0
	if !hasSel && !hasFlat {
		return ""
	}
	flatPart := ""
	if hasFlat {
		flatPart = strList(flat)
	}
	if !hasSel {
		return flatPart
	}
	// The "//conditions:default" arm is rendered LAST and exactly once.
	// When the caller's select map carries an explicit
	// "//conditions:default" delta (a platform if-chain's else() arm,
	// recovered by the #217 partition), its items populate that arm
	// instead of the empty list — emitting it as a normal key would
	// produce a duplicate "//conditions:default" key, which Bazel
	// rejects.
	defaultArm := sel["//conditions:default"]
	keys := make([]string, 0, len(sel))
	for k := range sel {
		if k == "//conditions:default" {
			continue
		}
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b bytes.Buffer
	b.WriteString("select({\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "        %q: %s,\n", k, indentArmList(sel[k]))
	}
	fmt.Fprintf(&b, "        %q: %s,\n", "//conditions:default", indentArmList(defaultArm))
	b.WriteString("    })")

	if hasFlat {
		return flatPart + " + " + b.String()
	}
	return b.String()
}

// indentArmList renders a select() arm's value as a Starlark
// list literal indented for a select({}) block at the cc-rule
// attribute level (8 spaces leading on continuation lines, with
// the closing bracket lining up with the arm's key column).
// Empty list → "[]" inline; non-empty → multi-line so each
// item gets its own line, regardless of brevity, because the
// surrounding select() is already multi-line and a single-line
// arm would visually clash.
//
// Items are rendered in the caller-supplied order: the
// elementfold layer already produces arms in the right order
// per attribute (lexicographic for srcs/hdrs/etc., original
// sequence for order-sensitive copts/linkopts), and any
// emit-time fan-in (e.g. cc_binary's hdrs→srcs fold) sorts
// its merged arm explicitly before passing it down. Sorting
// unconditionally here would re-order copts/linkopts deltas
// out of the sequence the operator wrote.
func indentArmList(items []string) string {
	if len(items) == 0 {
		return "[]"
	}
	var b bytes.Buffer
	b.WriteString("[\n")
	for _, s := range items {
		fmt.Fprintf(&b, "            %q,\n", s)
	}
	b.WriteString("        ]")
	return b.String()
}

// collapseToSingleLine maps any embedded newline / carriage return
// in a header-comment line to a single space, then collapses
// runs of whitespace introduced by the substitution. Used to keep
// the file-head `# <line>\n` shape stable when an upstream
// producer (cmake HELPSTRING, deprecation message, find_package
// attribution) carries multi-line text that would otherwise
// break the emitted comment block.
func collapseToSingleLine(s string) string {
	if !strings.ContainsAny(s, "\n\r") {
		return s
	}
	r := strings.NewReplacer("\r\n", " ", "\n", " ", "\r", " ")
	out := r.Replace(s)
	// Collapse adjacent spaces to one so "foo\n   bar" doesn't
	// render as "foo    bar".
	for strings.Contains(out, "  ") {
		out = strings.ReplaceAll(out, "  ", " ")
	}
	return strings.TrimSpace(out)
}
