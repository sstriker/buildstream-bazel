// Package bazel emits a BUILD.bazel file from the IR.
//
// M1 uses text/template for stable, easy-to-diff output and zero external
// deps. The plan calls for a buildtools-AST spike in week 1; if it's adopted,
// it replaces the template here without changing the Emit signature.
//
// Output is deterministic: every list attribute is sorted before emission.
package bazel

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
	"text/template"
	"time"

	"github.com/bazelbuild/buildtools/build"
	"github.com/sstriker/buildstream-bazel/converter/internal/bazelconstraints"
	"github.com/sstriker/buildstream-bazel/converter/internal/failure"
	"github.com/sstriker/buildstream-bazel/converter/ir"
)

// header is intentionally path-free so the emitted BUILD.bazel is
// byte-identical across runs, machines, and per-orchestration tmpdirs.
// The element / codebase the file belongs to is implicit in its
// on-disk location (out/elements/<name>/BUILD.bazel for orchestrator
// runs; whatever --out-build the operator passed for standalone runs).
const header = `# Generated by convert-element-cmake. DO NOT EDIT.

`

// ccRuleLoads maps each Kind to its rules_cc load symbol. Bazel 9
// removed cc_library/cc_binary/cc_import from the global namespace;
// every emitted BUILD.bazel using one of these rules must `load()`
// it explicitly. Older Bazels accept the load + load-less form alike.
var ccRuleLoads = map[ir.Kind]string{
	ir.KindCCLibrary:   "cc_library",
	ir.KindCCBinary:    "cc_binary",
	ir.KindCCImport:    "cc_import",
	ir.KindCCInterface: "cc_library",
	ir.KindCCTest:      "cc_test",
}

// emitPackageDefaultVisibility writes the file-head
// `package(default_visibility = ["//visibility:public"])` line
// that every generated BUILD carries. Gazelle / gazelle_cc
// canon: visibility is set once at the package level and
// per-rule `visibility` is emitted only when overriding the
// default. The corresponding per-rule suppression lives in
// nonDefaultVisibility (called from each ccView/ccImportView/
// shBinaryView/genruleView constructor), which drops the
// public default from each target's emitted attributes.
//
// This pairs with the per-rule logic: visibility set on a
// target that equals the package default is omitted from the
// emitted rule; a target with a different visibility (e.g.
// `//visibility:private` or a specific package_group) still
// emits its own visibility line, which Bazel treats as the
// override per the standard precedence.
func emitPackageDefaultVisibility(buf *bytes.Buffer) {
	buf.WriteString(`package(default_visibility = ["//visibility:public"])` + "\n\n")
}

// emitProvenanceComment writes a leading `# Source: <file>:<line>
// (<command>)` comment above the next emitted rule. Phase 1
// task 1 of the generator-parity uplift — the backtrace-derived
// annotation that tells the operator which cmake call site
// declared the target.
//
// File / Line / Command are written verbatim. The buildtools
// canonicalize pass preserves leading comments attached to rule
// calls, so the comment survives the formatter round-trip.
func emitProvenanceComment(buf *bytes.Buffer, p ir.Provenance) {
	buf.WriteString("# Source: ")
	buf.WriteString(p.File)
	if p.Line > 0 {
		buf.WriteString(":")
		buf.WriteString(itoa(p.Line))
	}
	if p.Command != "" {
		buf.WriteString(" (")
		buf.WriteString(p.Command)
		buf.WriteString(")")
	}
	buf.WriteString("\n")
}

// itoa is a tiny non-fmt int-to-string helper for the per-rule
// provenance comment's hot path. Avoids pulling fmt into emit's
// per-target loop.
func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	neg := n < 0
	if neg {
		n = -n
	}
	var b [20]byte
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	if neg {
		i--
		b[i] = '-'
	}
	return string(b[i:])
}

// defaultPublicVisibility is the package-level default emitted
// by emitPackageDefaultVisibility. Per-rule Visibility slices
// matching this exact list are suppressed by
// nonDefaultVisibility — the package default already covers
// them and a duplicate per-rule line would be noise that
// `gazelle fix` would later remove.
var defaultPublicVisibility = []string{"//visibility:public"}

// nonDefaultVisibility returns vis verbatim when it represents
// an override of the package-level default
// (//visibility:public), and nil when vis equals the package
// default. Centralizing the comparison here means every view
// constructor (ccView, ccImportView, shBinaryView,
// genruleView) emits the same elision policy without each
// having to spell out the public-default literal.
//
// vis is returned as a fresh slice in the override case so the
// caller can mutate freely without aliasing the IR-side
// Visibility slice; the IR is read-only from emit's
// perspective.
func nonDefaultVisibility(vis []string) []string {
	if len(vis) == len(defaultPublicVisibility) {
		match := true
		for i, v := range vis {
			if v != defaultPublicVisibility[i] {
				match = false
				break
			}
		}
		if match {
			return nil
		}
	}
	if len(vis) == 0 {
		return nil
	}
	return append([]string(nil), vis...)
}

// emitGazelleCcSearch writes `# gazelle:cc_search "" <pkgpath>/<dir>`
// file-head directives mirroring the union of every target's
// `includes` attribute values. Per ROADMAP.md
// Phase 7d: gazelle_cc's header-scan resolver needs the same
// include search paths the converter extracted from CMake so an
// operator-added unqualified `#include "X"` of an in-tree header
// resolves to the right label on `gazelle fix`.
//
// Frame mismatch the two-arg shape fixes: `cc_library.includes`
// is package-relative ("include" → `-I <pkgpath>/include` at
// compile time), whereas gazelle_cc's `cc_search` directive
// takes (<strip_include_prefix>, <include_prefix>) pairs
// interpreted **repo-root relative**, where `gazelle_cc` prepends
// `<include_prefix>` to the include text and looks the result up
// in `cc_index.json`. The directive that gives gazelle_cc the
// same name-resolution view the `-I <pkgpath>/include` flag
// gives the compiler is `# gazelle:cc_search "" <pkgpath>/include`
// — strip nothing, prepend the package-rooted include dir.
// The single-arg form we previously emitted left the second arg
// empty, which gazelle_cc treats as "strip leading <arg>/ from
// the include and look at the repo root" — wrong semantics.
//
// Inert when opts.BazelPackagePath is empty (the directive can't
// be correctly framed without the repo-relative package path) or
// when no target carries `includes`. Tests that don't care about
// gazelle_cc resolution pass the zero-value Options and get no
// directive, keeping their goldens shape-pure.
func emitGazelleCcSearch(buf *bytes.Buffer, pkg *ir.Package, opts Options) {
	if opts.BazelPackagePath == "" {
		return
	}
	seen := map[string]struct{}{}
	var dirs []string
	for _, t := range pkg.Targets {
		for _, d := range t.Includes {
			if _, ok := seen[d]; ok {
				continue
			}
			seen[d] = struct{}{}
			dirs = append(dirs, d)
		}
	}
	if len(dirs) == 0 {
		return
	}
	sort.Strings(dirs)
	pkgPath := strings.Trim(opts.BazelPackagePath, "/")
	for _, d := range dirs {
		// Join package path + include dir using the same
		// slash-rooted form gazelle_cc expects. Skip leading
		// "./" or "/" on the include dir for cleanliness; CMake
		// includes are normally simple package-relative names
		// ("include", "src") but defend against the occasional
		// "./include" the lower path might produce.
		rel := strings.TrimPrefix(strings.TrimPrefix(d, "./"), "/")
		// A "." include dir (the split-packages synthesized header
		// lib's own-package include) means "this package's root" —
		// emit the package path alone rather than "<pkg>/." so the
		// directive reads cleanly and gazelle_cc resolves it to the
		// package, not a literal "." subdir.
		if rel == "." || rel == "" {
			fmt.Fprintf(buf, "# gazelle:cc_search \"\" %s\n", pkgPath)
			continue
		}
		fmt.Fprintf(buf, "# gazelle:cc_search \"\" %s/%s\n", pkgPath, rel)
	}
	buf.WriteString("\n")
}

// emitLoad writes a single `load("@rules_cc//cc:defs.bzl", ...)` line
// covering every cc_* symbol used by pkg's targets. Symbols are sorted
// for byte-stability. Returns nothing if pkg has no cc_* targets.
func emitLoad(buf *bytes.Buffer, pkg *ir.Package) {
	used := map[string]struct{}{}
	for _, t := range pkg.Targets {
		if sym, ok := ccRuleLoads[t.Kind]; ok {
			used[sym] = struct{}{}
		}
	}
	if len(used) == 0 {
		return
	}
	syms := make([]string, 0, len(used))
	for s := range used {
		syms = append(syms, s)
	}
	sort.Strings(syms)
	buf.WriteString(`load("@rules_cc//cc:defs.bzl"`)
	for _, s := range syms {
		fmt.Fprintf(buf, ", %q", s)
	}
	buf.WriteString(")\n\n")
}

// emitInstallLoad writes the
// `load("@rules_buildstream_bazel//rules:install.bzl", "pick_file")`
// line when pkg emits any pick_file target (the round-2
// execute-process fallback shape). No-op otherwise so the cc-only
// BUILD output stays byte-stable.
func emitInstallLoad(buf *bytes.Buffer, pkg *ir.Package) {
	for _, t := range pkg.Targets {
		if t.Kind == ir.KindPickFile {
			buf.WriteString(`load("@rules_buildstream_bazel//rules:install.bzl", "pick_file")` + "\n\n")
			return
		}
	}
}

// emitPkgFilesLoad writes the
// `load("@rules_pkg//pkg:mappings.bzl", "pkg_files")` line when pkg
// emits any pkg_files target (the install(FILES)/install(DIRECTORY)
// declarative-packaging shape, Phase 1 slice 1b). No-op otherwise so
// the cc-only / filegroup-only BUILD output stays byte-stable — an
// element with no install(FILES) emits no rules_pkg load and the
// consuming MODULE.bazel needs no rules_pkg bazel_dep. The
// corresponding write-a-side dep wiring lives in moduleBazelB.
func emitPkgFilesLoad(buf *bytes.Buffer, pkg *ir.Package) {
	hasPkgFiles := false
	hasStripPrefix := false
	for _, t := range pkg.Targets {
		if t.Kind != ir.KindPkgFiles {
			continue
		}
		hasPkgFiles = true
		// The install(DIRECTORY) glob shape renders
		// `strip_prefix.from_pkg(...)`, which needs the `strip_prefix`
		// symbol loaded alongside `pkg_files`. install(FILES) targets
		// (literal srcs list, no strip_prefix) don't, so a FILES-only
		// BUILD keeps the single-symbol load — preserving the
		// file-case output byte-for-byte.
		if t.PkgSrcsGlob && t.PkgStripPrefix != "" {
			hasStripPrefix = true
		}
	}
	if !hasPkgFiles {
		return
	}
	if hasStripPrefix {
		buf.WriteString(`load("@rules_pkg//pkg:mappings.bzl", "pkg_files", "strip_prefix")` + "\n\n")
		return
	}
	buf.WriteString(`load("@rules_pkg//pkg:mappings.bzl", "pkg_files")` + "\n\n")
}

// Options tunes the BUILD.bazel emission. Zero-value Options
// preserves the legacy relative-path emission.
type Options struct {
	// SourceKey, when non-empty, prefixes every source path in
	// emitted cc_library/cc_binary/cc_test `srcs = [...]` with
	// "@src_<SourceKey>//:" so project B references the bytes
	// by digest-stable Bazel label rather than by local
	// filesystem path. Used by the FUSE-sources route to keep
	// project B's compile actions BwoB without a project-B-side
	// FUSE mount of its own.
	SourceKey string

	// Header overrides the default "# Generated by
	// convert-element-cmake. DO NOT EDIT.\n\n" file-head comment.
	// Multiple cmd/* binaries share this emitter (convert-
	// element / convert-element-meson / convert-element-trace
	// / fold-element); each can attribute its own output via
	// Header so the operator-visible provenance comment names
	// the actual binary that produced the file. Must end with
	// a trailing "\n\n" if the caller wants a blank line
	// separating the header from the rest of the BUILD; this
	// field is appended verbatim to the buffer.
	Header string

	// BazelPackagePath is the repo-root-relative path of the
	// Bazel package the emitted BUILD.bazel lives in (e.g.
	// "elements/hello-world"). Used to frame the
	// `# gazelle:cc_search "" <pkgpath>/<include>` directives so
	// gazelle_cc's header-scan resolver sees the same include
	// search paths the converter extracted from CMake.
	// gazelle_cc interprets `cc_search` arguments repo-root
	// relative, whereas `cc_library.includes` is package-relative
	// — without the package-path frame the directive points at
	// the wrong place. Empty value (zero Options) suppresses the
	// directive entirely, which is the right shape for unit
	// tests that don't care about gazelle_cc resolution.
	BazelPackagePath string

	// EmitProvenance enables Phase 1 task 1's backtrace-derived
	// per-rule annotation: when true, each rule whose Target has
	// a non-zero Provenance gets a leading
	// `# Source: <file>:<line> (<command>)` comment. Operators
	// use the annotation to navigate "why does this Bazel target
	// exist?" without re-running the converter.
	//
	// Off by default — comments change BUILD output bytes and
	// would invalidate every existing golden if always-on. CLI
	// surface via `convert-element-cmake --emit-provenance`.
	EmitProvenance bool
}

// Emit returns the contents of a BUILD.bazel file for pkg using
// default Options.
func Emit(pkg *ir.Package) ([]byte, error) {
	return EmitWithOptions(pkg, Options{})
}

// EmitWithOptions is the configurable form of Emit.
//
// The emitter constructs each rule via the in-package text
// templates and then routes the assembled output through
// `bazel.build/buildtools/build`'s Parse + Format pipeline —
// the same pipeline `buildifier --mode=fix` uses. That gives
// project B the Phase 3 contract from
// ROADMAP.md: `buildifier
// --mode=fix` against our generated BUILDs is a no-op (we
// emit what buildifier would produce). Side effect: attribute
// order pulls from buildtools' `tables.NamePriority` rather
// than the template's manual order, so the rendered shape
// matches what an operator hand-formatting via buildifier
// would see post-conversion.
func EmitWithOptions(pkg *ir.Package, opts Options) ([]byte, error) {
	// Pre-emit constraint pass. Catches the small set of
	// Bazel-side semantic violations that have produced real
	// operator bugs (empty genrule cmd #193, duplicate deps
	// #194, malformed rule names) before they hit disk. See
	// converter/internal/bazelconstraints for the constraint
	// list and the rationale per check.
	if err := bazelconstraints.ValidatePackage(pkg); err != nil {
		return nil, fmt.Errorf("bazel constraint violation: %w", err)
	}
	var buf bytes.Buffer
	if opts.Header != "" {
		buf.WriteString(opts.Header)
	} else {
		buf.WriteString(header)
	}
	// Package-level header comments — find_package resolutions
	// and other attribution data the lifter wants to surface.
	// Collapse any embedded newlines / carriage returns to spaces
	// so a multi-line cmake HELPSTRING (LLVM's
	// `option(LLVM_BUILD_BENCHMARKS "Add ...\ntargets. If OFF
	// ...")` shape) doesn't break the comment block by emitting an
	// unprefixed continuation line that Bazel parses as bare
	// syntax. Producers in lower/ aren't aware of this constraint;
	// the emit-side scrub keeps every producer safe by
	// construction.
	for _, line := range pkg.HeaderComments {
		buf.WriteString("# ")
		buf.WriteString(collapseToSingleLine(line))
		buf.WriteString("\n")
	}
	if len(pkg.HeaderComments) > 0 {
		buf.WriteString("\n")
	}
	emitGazelleCcSearch(&buf, pkg, opts)
	emitLoad(&buf, pkg)
	emitInstallLoad(&buf, pkg)
	emitPkgFilesLoad(&buf, pkg)
	emitWriteFileLoad(&buf, pkg)
	emitBoolFlagLoad(&buf, pkg)
	emitCMakeConfigureFileLoad(&buf, pkg)
	emitPackageDefaultVisibility(&buf)

	for i, t := range pkg.Targets {
		if i > 0 {
			buf.WriteString("\n")
		}
		if opts.EmitProvenance && !t.Provenance.IsZero() {
			emitProvenanceComment(&buf, t.Provenance)
		}
		if t.Kind == ir.KindGenrule {
			if err := emitGenrule(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if t.Kind == ir.KindCCImport {
			if err := emitCCImport(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if t.Kind == ir.KindShBinary {
			if err := emitShBinary(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if t.Kind == ir.KindPickFile {
			if err := emitPickFile(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if t.Kind == ir.KindFilegroup {
			if err := emitFilegroup(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if t.Kind == ir.KindPkgFiles {
			if err := emitPkgFiles(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if t.Kind == ir.KindAlias {
			if err := emitAlias(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if t.Kind == ir.KindWriteFile {
			if err := emitWriteFile(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if t.Kind == ir.KindCMakeConfigureFile {
			if err := emitCMakeConfigureFile(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if t.Kind == ir.KindBoolFlag {
			if err := emitBoolFlag(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if t.Kind == ir.KindConfigSetting {
			if err := emitConfigSetting(&buf, t); err != nil {
				return nil, err
			}
			continue
		}
		if err := emitCCTargetWithOptions(&buf, t, opts); err != nil {
			return nil, err
		}
	}
	return canonicalize(buf.Bytes())
}

// canonicalize routes the template-assembled BUILD text
// through buildtools' Parse + Format pipeline so the final
// output matches what `buildifier --mode=fix` would produce.
// Attribute order pulls from `tables.NamePriority`; list
// wrapping, quote normalization, and load() symbol sorting
// fall out of the formatter's default Rewriter pass.
//
// We use a synthetic filename ending in `BUILD.bazel` so
// buildtools parses with TypeBuild semantics (it dispatches
// off the path basename). The bytes never touch disk; the
// name is purely a parse-mode hint.
//
// On a parse error we return a typed Tier-1 `*failure.Error`
// with code `BazelCanonicalizeFailed` carrying both the
// buildtools diagnostic and the offending body. The typed
// failure means convert-element-cmake's handleError surfaces
// the operator-friendly failure.json without per-caller
// wrapping — keeping the typed-code contract LOCAL to the
// failure site so a future emit-side error of a different
// shape (e.g. a new constraint check) doesn't inherit the
// `bazel-canonicalize-failed` label by mistake.
//
// Test code that drives canonicalize directly (see
// `keep_markers_test`) sees the same typed error and can
// match on `failure.BazelCanonicalizeFailed`. The pre-#210
// shape — an uncaught panic — silently broke the
// buildifier-no-op contract without a test-visible trigger;
// the typed return surfaces it loudly in both unit tests
// and production paths.
func canonicalize(body []byte) ([]byte, error) {
	f, err := build.Parse("BUILD.bazel", body)
	if err != nil {
		return nil, failure.New(failure.BazelCanonicalizeFailed,
			"bazel.canonicalize: template emitted unparseable BUILD bytes: %v\n%s", err, body)
	}
	addKeepMarkers(f)
	return build.Format(f), nil
}

// addKeepMarkers walks every rule in f and tags load-bearing
// attribute lines (and whole rules, for genrule / filegroup)
// with `# keep` comments. Per docs/design/build-output-
// conventions.md's Phase 7a roundtrip spec: these markers
// prevent a downstream `gazelle fix` run from rewriting
// values the converter extracted from CMake/Meson/trace —
// signals gazelle wouldn't be able to re-derive from
// post-conversion sources alone.
//
// The marker scope follows the conventions doc's table:
//
//   - cc_library / cc_binary / cc_test: copts, defines,
//     linkopts, includes, tags, linkstatic, alwayslink,
//     include_prefix, strip_include_prefix.
//   - cc_test additionally: args, env, timeout, data.
//   - cc_import + alias + pkg_files: whole-rule keep. gazelle /
//     gazelle_cc can't regenerate install-export imports (the
//     round-2 fallback's library exports), aliases, or the
//     install(FILES)/install(DIRECTORY)-derived pkg_files
//     packaging rules from post-conversion sources, so a
//     rule-level keep is the only scope that survives a gazelle
//     maintenance pass — an attribute-level keep leaves the rule
//     itself a deletion candidate when gazelle finds no source to
//     back it.
//   - genrule + filegroup: whole-rule keep (closing-paren
//     suffix comment).
//   - package(...): whole-rule keep.
//
// The marker doesn't trigger when gazelle isn't installed —
// it's an inert # comment to any tool that doesn't look for
// it. Phase 3's buildifier-canonical contract is preserved:
// buildifier honors the keep markers and doesn't reformat
// the tagged lines.
func addKeepMarkers(f *build.File) {
	for _, stmt := range f.Stmt {
		call, ok := stmt.(*build.CallExpr)
		if !ok {
			continue
		}
		kind := callRuleKind(call)
		switch kind {
		case "genrule", "filegroup", "package", "cc_import", "alias", "pkg_files", "write_file", "cmake_configure_file":
			markCallKeep(call)
		case "cc_library", "cc_binary", "cc_test":
			if kind == "cc_library" && callHasTag(call, generatedHeadersTag) {
				// The fully synthesized generated-header wrapper has no
				// on-disk srcs for gazelle to reconcile it against — a
				// maintenance pass would delete it. Whole-rule keep pins it.
				// Keyed on the tag, not the name, so a user rule that shares
				// the name is left for gazelle to manage.
				markCallKeep(call)
			} else {
				markAttrsKeep(call, ccKeepAttrs(kind))
				markGeneratedHeaderDeps(call)
			}
		}
	}
}

// callHasTag reports whether a rule call's `tags` attribute (a plain list
// literal) contains tag. Used to recognize converter-synthesized rules by
// their tag rather than a collidable name.
func callHasTag(call *build.CallExpr, tag string) bool {
	for _, arg := range call.List {
		assign, ok := arg.(*build.AssignExpr)
		if !ok {
			continue
		}
		ident, ok := assign.LHS.(*build.Ident)
		if !ok || ident.Name != "tags" {
			continue
		}
		list, ok := assign.RHS.(*build.ListExpr)
		if !ok {
			continue
		}
		for _, item := range list.List {
			if str, ok := item.(*build.StringExpr); ok && str.Value == tag {
				return true
			}
		}
	}
	return false
}

// callRuleKind returns the rule kind for a CallExpr (e.g.
// "cc_library", "genrule") or "" if the call's function
// position isn't a bare identifier. Top-level BUILD calls
// are typically Ident-headed; load() is the exception (it's
// an Ident but routed elsewhere via stmt type).
func callRuleKind(call *build.CallExpr) string {
	if ident, ok := call.X.(*build.Ident); ok {
		return ident.Name
	}
	return ""
}

// markCallKeep appends a `# keep` suffix comment to the
// CallExpr itself. The formatter renders this on the line
// of the closing `)` of the call.
func markCallKeep(call *build.CallExpr) {
	if hasKeepSuffix(call.Comment().Suffix) {
		return
	}
	call.Comment().Suffix = append(call.Comment().Suffix, build.Comment{Token: "# keep"})
}

// markAttrsKeep walks the call's positional/keyword args
// and tags each AssignExpr whose LHS is one of attrNames
// with a `# keep` suffix.
func markAttrsKeep(call *build.CallExpr, attrNames map[string]bool) {
	if len(attrNames) == 0 {
		return
	}
	for _, arg := range call.List {
		assign, ok := arg.(*build.AssignExpr)
		if !ok {
			continue
		}
		ident, ok := assign.LHS.(*build.Ident)
		if !ok {
			continue
		}
		if !attrNames[ident.Name] {
			continue
		}
		if hasKeepSuffix(assign.Comment().Suffix) {
			continue
		}
		assign.Comment().Suffix = append(assign.Comment().Suffix, build.Comment{Token: "# keep"})
	}
}

// markGeneratedHeaderDeps tags each `deps` list item that references a
// synthesized generated-header wrapper library (label suffix
// `:generated_headers`, see split.go's generatedHeadersName) with a
// per-item `# keep`. gazelle's cc extension resolves deps from #include
// directives; it can't resolve a generated `.inc` to the wrapper (the file
// isn't on disk at gazelle time), so without the marker a maintenance pass
// would strip the edge. Per-item (not whole-attr) so gazelle still manages
// the consumer's ordinary, resolvable deps.
func markGeneratedHeaderDeps(call *build.CallExpr) {
	for _, arg := range call.List {
		assign, ok := arg.(*build.AssignExpr)
		if !ok {
			continue
		}
		ident, ok := assign.LHS.(*build.Ident)
		if !ok || ident.Name != "deps" {
			continue
		}
		list, ok := assign.RHS.(*build.ListExpr)
		if !ok {
			continue
		}
		for _, item := range list.List {
			str, ok := item.(*build.StringExpr)
			if !ok {
				continue
			}
			if !strings.HasSuffix(str.Value, ":"+generatedHeadersName) {
				continue
			}
			if hasKeepSuffix(str.Comment().Suffix) {
				continue
			}
			str.Comment().Suffix = append(str.Comment().Suffix, build.Comment{Token: "# keep"})
		}
	}
}

// hasKeepSuffix reports whether the comment slice already
// contains a `# keep` marker. Used to make addKeepMarkers
// idempotent — calling canonicalize twice on the same body
// (e.g. round-tripping through write-a's BUILD.bazel
// canonicalize plus the embedded one here) doesn't double
// up markers.
func hasKeepSuffix(comments []build.Comment) bool {
	for _, c := range comments {
		if strings.TrimSpace(c.Token) == "# keep" {
			return true
		}
	}
	return false
}

// ccKeepAttrs returns the set of attribute names that
// receive `# keep` markers for a cc_* rule kind. cc_test
// gets the cc_library set plus its test-only attributes.
func ccKeepAttrs(kind string) map[string]bool {
	base := map[string]bool{
		"copts":                true,
		"defines":              true,
		"linkopts":             true,
		"includes":             true,
		"tags":                 true,
		"linkstatic":           true,
		"alwayslink":           true,
		"include_prefix":       true,
		"strip_include_prefix": true,
		// textual_hdrs are x-macro / generated `.inc` fragments gazelle's
		// cc extension can't resolve from disk (a tablegen output isn't
		// present at gazelle time); keep them so a maintenance pass doesn't
		// strip the generated-header wrapper's contents.
		"textual_hdrs": true,
	}
	if kind == "cc_test" {
		base["args"] = true
		base["env"] = true
		base["timeout"] = true
		base["data"] = true
	}
	return base
}

