func emitCCTargetWithOptions(w *bytes.Buffer, t ir.Target, opts Options) error {
	// Compute the per-attribute baselines first (matching the
	// existing single-platform sort/order conventions), then fold
	// in any per-platform deltas. cc_binary / cc_test fold their
	// hdrs into srcs before rendering; the FUSE source-label
	// rewrite applies after that fold. PerPlatform deltas are
	// rewritten with the same source-label prefix where they
	// describe per-platform srcs/hdrs.
	srcs := sortedCopy(t.Srcs)
	hdrs := sortedCopy(t.Hdrs)
	includes := sortedCopy(t.Includes)
	copts := append([]string(nil), t.Copts...) // preserve order; flag order matters
	defines := sortedCopy(t.Defines)
	linkopts := append([]string(nil), t.LinkOpts...) // preserve order
	deps := sortedCopy(t.Deps)
	implementationDeps := sortedCopy(t.ImplementationDeps)

	// cc_binary doesn't accept `hdrs` (Bazel 9 errors out where
	// older versions silently ignored). Fold any header into srcs
	// so the translation unit still sees them, even though that's
	// the rules_cc convention for binaries. cc_test inherits
	// cc_binary's stricture, so apply the same fold there.
	srcsSel := perPlatformAttr(t, "srcs")
	hdrsSel := perPlatformAttr(t, "hdrs")
	if (t.Kind == ir.KindCCBinary || t.Kind == ir.KindCCTest) && (len(hdrs) > 0 || len(hdrsSel) > 0) {
		srcs = append(srcs, hdrs...)
		sort.Strings(srcs)
		hdrs = nil
		// Per-platform hdrs deltas fold into the corresponding
		// srcs delta arms so cc_binary/cc_test still see those
		// headers as compilation inputs in their respective
		// platforms.
		if len(hdrsSel) > 0 {
			if srcsSel == nil {
				srcsSel = map[string][]string{}
			}
			for arm, items := range hdrsSel {
				srcsSel[arm] = append(srcsSel[arm], items...)
				// srcs is not order-sensitive: sort the merged
				// arm so it matches the baseline path's
				// sort-after-fold convention and so renders
				// stably regardless of cell iteration order.
				sort.Strings(srcsSel[arm])
			}
		}
		hdrsSel = nil
	}

	// FUSE-sources path: rewrite src + hdr paths to @src_<key>//:
	// labels so project B compiles against digest-referenced
	// inputs rather than relative paths. The `@…//:<path>` form
	// preserves the path exactly (no leading slash) — Bazel's
	// label parser handles it. Per-platform delta arms get the
	// same rewrite for the same reason.
	if opts.SourceKey != "" {
		srcs = prefixWithSourceLabel(srcs, opts.SourceKey)
		hdrs = prefixWithSourceLabel(hdrs, opts.SourceKey)
		srcsSel = prefixSelectWithSourceLabel(srcsSel, opts.SourceKey)
		hdrsSel = prefixSelectWithSourceLabel(hdrsSel, opts.SourceKey)
	}

	v := ccView{
		RuleKind:                   t.Kind.String(),
		Name:                       t.Name,
		SrcsExpr:                   attrExpr(srcs, srcsSel),
		HdrsExpr:                   attrExpr(hdrs, hdrsSel),
		TextualHdrsExpr:            attrExpr(sortedCopy(t.TextualHdrs), perPlatformAttr(t, "textual_hdrs")),
		IncludesExpr:               attrExpr(includes, perPlatformAttr(t, "includes")),
		IncludePrefix:              t.IncludePrefix,
		StripIncludePrefix:         t.StripIncludePrefix,
		CoptsExpr:                  attrExpr(copts, perPlatformAttr(t, "copts")),
		DefinesExpr:                attrExpr(defines, perPlatformAttr(t, "defines")),
		LocalDefinesExpr:           attrExpr(sortedCopy(t.LocalDefines), perPlatformAttr(t, "local_defines")),
		LinkoptsExpr:               attrExpr(linkopts, perPlatformAttr(t, "linkopts")),
		AdditionalLinkerInputsExpr: attrExpr(t.AdditionalLinkerInputs, nil),
		DepsExpr:                   attrExpr(deps, perPlatformAttr(t, "deps")),
		ImplementationDepsExpr:     attrExpr(implementationDeps, perPlatformAttr(t, "implementation_deps")),
		Linkstatic:                 t.Linkstatic,
		Alwayslink:                 t.Alwayslink,
		Features:                   sortedCopy(t.Features),
		// Data lifts cmake's add_dependencies-derived build-order
		// edges (set via the per-target backtrace recovery in
		// lower). cc_test additionally appends t.TestData below
		// for set_tests_properties WORKING_DIRECTORY etc.
		Data:       sortedCopy(t.Data),
		Tags:       sortedCopy(t.Tags),
		Visibility: nonDefaultVisibility(t.Visibility),
	}
	if t.Kind == ir.KindCCTest {
		v.Args = append([]string(nil), t.TestArgs...) // preserve order; arg order matters
		// cc_test: merge t.Data (add_dependencies-derived) with
		// t.TestData (set_tests_properties), sorted + deduped.
		merged := append([]string(nil), v.Data...)
		merged = append(merged, t.TestData...)
		v.Data = sortedDedup(merged)
		if t.TestTimeout > 0 {
			v.Timeout = formatBazelTimeout(t.TestTimeout)
		}
		if len(t.TestEnv) > 0 {
			v.Env = make(map[string]string, len(t.TestEnv))
			for _, kv := range t.TestEnv {
				if i := strings.IndexByte(kv, '='); i >= 0 {
					v.Env[kv[:i]] = kv[i+1:]
				}
			}
		}
	}
	return ccRuleTmpl.Execute(w, v)
}

// perPlatformScalarAttr returns the per-platform scalar delta map
// for the named attribute. Nil-safe: returns nil when the IR
// target has no PerPlatformScalar map or no entry for the
// requested name. Used by emitCCImport for static_library /
// shared_library, which are single-string attrs (cc_import's
// path attrs) that fold differently from the list-shaped
// PerPlatform.
func perPlatformScalarAttr(t ir.Target, name string) map[string]string {
	if len(t.PerPlatformScalar) == 0 {
		return nil
	}
	m, ok := t.PerPlatformScalar[name]
	if !ok || len(m) == 0 {
		return nil
	}
	out := make(map[string]string, len(m))
	for k, v := range m {
		out[k] = v
	}
	return out
}

// scalarAttrExpr renders a single-string cc-rule attribute's
// value. Returns:
//
//   - "" when both flat and sel are empty (caller omits the
//     attribute entirely — cc_import targets that only carry one
//     of static_library / shared_library leave the other empty).
//   - the quoted literal when sel is empty (single-platform
//     shape; byte-identical to the pre-PerPlatformScalar
//     emission).
//   - a `select({...})` block with a trailing
//     `"//conditions:default": None` arm when sel is non-empty.
//     Unlike the list case there's no `<flat> + select()` form
//     (scalars don't compose under "+"), but the default arm IS
//     present so in-matrix platforms without a value for this
//     attribute fall through to "attribute unset" rather than
//     hitting a missing-arm analysis error. The partial-platform
//     cc_import case — linux has only static_library, darwin has
//     only shared_library — needs this: a build for darwin sees
//     `static_library = select({linux: "...", "//conditions:default": None})`
//     and Bazel treats static_library as unset (cc_import's
//     default), the right outcome instead of an analysis error.
//     Out-of-matrix platforms also resolve to None (attribute
//     unset), which matches the "this target doesn't apply
//     outside the declared matrix" semantic.
func scalarAttrExpr(flat string, sel map[string]string) string {
	hasSel := len(sel) > 0
	hasFlat := flat != ""
	if !hasSel && !hasFlat {
		return ""
	}
	if !hasSel {
		return fmt.Sprintf("%q", flat)
	}
	keys := make([]string, 0, len(sel))
	for k := range sel {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	b.WriteString("select({\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "        %q: %q,\n", k, sel[k])
	}
	b.WriteString(`        "//conditions:default": None,` + "\n")
	b.WriteString("    })")
	return b.String()
}

// perPlatformAttr returns the per-platform delta map for the
// named attribute. Nil-safe: returns nil when the IR target has
// no PerPlatform map at all or no entry for the requested name.
// The returned map is a shallow copy so emit-time mutations
// (the cc_binary hdrs→srcs fold) don't bleed back into the
// caller's IR.
func perPlatformAttr(t ir.Target, name string) map[string][]string {
	if len(t.PerPlatform) == 0 {
		return nil
	}
	m, ok := t.PerPlatform[name]
	if !ok || len(m) == 0 {
		return nil
	}
	out := make(map[string][]string, len(m))
	for k, v := range m {
		out[k] = append([]string(nil), v...)
	}
	return out
}

// prefixSelectWithSourceLabel applies prefixWithSourceLabel to
// every arm of a select()-shaped delta map. Returns nil for nil
// input so a "no delta" signal stays a "no delta" signal.
func prefixSelectWithSourceLabel(sel map[string][]string, key string) map[string][]string {
	if sel == nil {
		return nil
	}
	out := make(map[string][]string, len(sel))
	for arm, items := range sel {
		out[arm] = prefixWithSourceLabel(items, key)
	}
	return out
}

// prefixWithSourceLabel maps relative source paths to
// @src_<key>//:tree_dir/<path> Bazel labels. The tree_dir/
// segment matches the repo rule's layout: rules/sources.bzl's
// _src_repo_impl ctx.symlinks the FUSE mount under tree_dir/
// inside the @src_<key>// repo and exports every path under
// it via exports_files(glob(["tree_dir/**"])). The label form
// preserves the relative path exactly under that prefix.
//
// Returns a fresh slice so the caller's view stays untouched on
// the legacy (non-fuse) path.
func prefixWithSourceLabel(paths []string, key string) []string {
	if len(paths) == 0 {
		return paths
	}
	out := make([]string, len(paths))
	for i, p := range paths {
		out[i] = "@src_" + key + "//:tree_dir/" + p
	}
	return out
}

// formatBazelTimeout maps a CTest TIMEOUT (a duration in seconds) to the
// Bazel test-rule `timeout` attribute, which is a fixed ENUM — "short"
// (≤60s), "moderate" (≤300s), "long" (≤900s), "eternal" (>900s) — NOT a
// duration string. Bazel rejects a duration like "120s" on a test rule's
// `timeout` at load time ("must be short, moderate, long, or eternal"), so
// CTest's integer seconds is bucketed into the smallest enum whose default
// budget covers it — except that "eternal" is the ceiling: a TIMEOUT beyond
// eternal's default (commonly 3600s) still maps to "eternal" as the largest
// available bucket (best effort; an operator can raise it with
// --test_timeout if a test genuinely needs longer). (Issue #314.)
func formatBazelTimeout(d time.Duration) string {
	switch {
	case d <= 60*time.Second:
		return "short"
	case d <= 300*time.Second:
		return "moderate"
	case d <= 900*time.Second:
		return "long"
	default:
		return "eternal"
	}
}

