// cmakeConfigureFileView projects ir.Target / CMakeConfigureFileSpec into
// the cmake_configure_file template. The dict-valued attributes are
// pre-rendered Starlark literals; the optional ones carry "" to signal
// omission (the template's `{{- if }}` guards). values is always emitted
// (even "{}") since the empty map is a meaningful COPYONLY lift.
type cmakeConfigureFileView struct {
	Name                string
	Out                 string
	Template            string
	ContentLiteral      string
	Values              string
	StampValues         string
	GenexValues         string
	GenexContext        string // truthiness guard
	GenexContextLiteral string
	TargetFiles         string
	TargetObjects       string
	Tool                string
	AtOnly              bool
	CopyOnly            bool
	EscapeQuotes        bool
	NewlineStyle        string
	Tags                []string
	Visibility          []string
}

func emitCMakeConfigureFile(w *bytes.Buffer, t ir.Target) error {
	s := t.CMakeConfigureFile
	if s == nil {
		return fmt.Errorf("emit cmake_configure_file %q: nil CMakeConfigureFile spec", t.Name)
	}
	v := cmakeConfigureFileView{
		Name:           t.Name,
		Out:            s.Out,
		Template:       s.Template,
		ContentLiteral: fmt.Sprintf("%q", s.Content),
		Values:         strDict(s.Values),
		Tool:           s.Tool,
		AtOnly:         s.AtOnly,
		CopyOnly:       s.CopyOnly,
		EscapeQuotes:   s.EscapeQuotes,
		NewlineStyle:   s.NewlineStyle,
		Tags:           sortedCopy(t.Tags),
		Visibility:     nonDefaultVisibility(t.Visibility),
	}
	// stamp_values omitted (left "") for the common non-stamp configure_file;
	// rendered as a readable string_dict when a VCS-stamp var feeds it.
	if len(s.StampValues) > 0 {
		v.StampValues = strDict(s.StampValues)
	}
	if len(s.GenexValuesPerConfig) > 0 {
		// Per-config divergence → render the genex_values attr as a select()
		// over the //config:<name> arms. The rule's string_dict attr is
		// configurable, so Bazel resolves the active config's map before the
		// rule impl runs (no rule change needed).
		v.GenexValues = renderConfigDictSelect(s.GenexValuesPerConfig)
	} else if len(s.GenexValues) > 0 {
		v.GenexValues = strDict(s.GenexValues)
	}
	if s.GenexContext != "" {
		v.GenexContext = s.GenexContext
		v.GenexContextLiteral = fmt.Sprintf("%q", s.GenexContext)
	}
	if len(s.TargetFiles) > 0 {
		v.TargetFiles = strDict(s.TargetFiles)
	}
	if len(s.TargetObjects) > 0 {
		v.TargetObjects = strDict(s.TargetObjects)
	}
	return cmakeConfigureFileTmpl.Execute(w, v)
}

// renderConfigDictSelect renders a per-config map (config label -> string dict)
// as a Starlark `select({...})` expression for the genex_values attribute. Keys
// are the `//config:<name>` labels the multi-config //config package backs;
// build_type's string_flag default always resolves to one of them, so no
// `//conditions:default` arm is needed. canonicalize() reformats the result, so
// this only has to emit a valid select() with sorted, byte-stable arms.
func renderConfigDictSelect(perConfig map[string]map[string]string) string {
	labels := make([]string, 0, len(perConfig))
	for l := range perConfig {
		labels = append(labels, l)
	}
	sort.Strings(labels)
	var b bytes.Buffer
	b.WriteString("select({\n")
	for _, l := range labels {
		fmt.Fprintf(&b, "        %q: %s,\n", l, strDict(perConfig[l]))
	}
	b.WriteString("    })")
	return b.String()
}

